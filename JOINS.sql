USE ECOMMERCE_DB;

SELECT PRODUCTS.PRODUCT_ID,PRODUCTS.PRODUCT_NAME,CATEGORIES.CATEGORY_NAME
FROM PRODUCTS
INNER JOIN CATEGORIES
ON PRODUCTS.CATEGORY_ID=CATEGORIES.CATEGORY_ID;

#Display customers and their orders.
SELECT CUSTOMERS.CUSTOMER_ID,CUSTOMERS.FIRST_NAME,CUSTOMERS.LAST_NAME,
ORDERS.ORDER_ID FROM CUSTOMERS
LEFT JOIN ORDERS
ON CUSTOMERS.CUSTOMER_ID=ORDERS.CUSTOMER_ID;

#Display each order with customer name and order status.
SELECT ORDERS.ORDER_ID, CUSTOMERS.FIRST_NAME,CUSTOMERS.LAST_NAME,ORDERS.STATUS
FROM ORDERS
LEFT JOIN CUSTOMERS
ON CUSTOMERS.CUSTOMER_ID=ORDERS.CUSTOMER_ID;

#Display each order item with product name, quantity, and unit price.
SELECT ORDER_ITEMS.ORDER_ID,ORDER_ITEMS.QUANTITY,ORDER_ITEMS.UNIT_PRICE, PRODUCTS.PRODUCT_NAME
FROM ORDER_ITEMS 
LEFT JOIN PRODUCTS 
ON ORDER_ITEMS.PRODUCT_ID=PRODUCTS.PRODUCT_ID;




